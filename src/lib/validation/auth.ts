// =====================================================================
// Validation schemas — فورم الـ Login وفورم الـ Register
// ---------------------------------------------------------------------
// الملف ده بيستخدم مكتبة zod. الفكرة إنك بتوصف "شكل البيانات الصح"
// مرة واحدة (اسمه schema)، وبعدين تقول لـ zod:
//
//     const result = loginSchema.safeParse(البيانات اللي اليوزر كتبها);
//
// - لو البيانات سليمة:  result.success = true  و result.data فيها البيانات
//   بعد التنضيف (زي شيل المسافات وتصغير حروف الأيميل).
// - لو فيها غلط:        result.success = false و result.error فيه كل
//   الأخطاء، كل خانة ورسالتها.
//
// الفورمز بتعمل الـ validation ده في المتصفح قبل ما تبعت أي request،
// فاليوزر بيشوف الغلط تحت الخانة على طول من غير ما نستنى السيرفر.
//
// مهم: ده مش بديل للـ validation اللي في الباك أند. الداتابيز برضه
// بتتأكد بنفسها (check constraints وغيرها)، لأن أي حد يقدر يبعت request
// من Postman من غير ما يعدي على الفورم خالص.
//
// مين بيستخدم الملف ده:
//   - src/app/(auth)/login/login-form.tsx        ← loginSchema
//   - src/app/(auth)/register/register-form.tsx  ← registerSchema
// =====================================================================

import { z } from "zod";

// ---------------------------------------------------------------------
// رقم الموبايل المصري (Regular Expression)
//   ^01        → لازم يبدأ بـ 01
//   [0125]     → الرقم التالت: 0 فودافون، 1 اتصالات، 2 أورانج، 5 وي
//   [0-9]{8}   → وبعدهم 8 أرقام بالظبط
//   $          → ومفيش أي حاجة بعدهم
// يعني الرقم كله 11 رقم. ونفس الـ regex ده موجود في الداتابيز
// (check constraint على عمود phone)، فالاتنين متفقين.
// ---------------------------------------------------------------------
const EG_MOBILE = /^01[0125][0-9]{8}$/;

// =====================================================================
// loginSchema: فورم تسجيل الدخول
// =====================================================================
export const loginSchema = z.object({
  // z.email("...")   → لازم يبقى أيميل صيغته صح (فيه @ ونقطة ...).
  //                     والنص اللي بين القوسين هو رسالة الخطأ اللي هتظهر.
  // .trim()          → بيشيل المسافات من الأول والآخر، علشان لو اليوزر
  //                     عمل paste وجه معاه مسافة.
  // .toLowerCase()   → بيصغّر الحروف: Ahmed@Gmail.com تبقى ahmed@gmail.com
  //                     علشان الأيميل يطابق اللي متسجل.
  email: z.email("اكتب أيميل صحيح").trim().toLowerCase(),

  // z.string()       → لازم يبقى نص.
  // .min(1, "...")   → على الأقل حرف واحد، يعني مش فاضي.
  // ملحوظة: في الـ Login مش بنتشيك على طول الباسوورد (8 حروف مثلاً)،
  // لأن ده شغل صفحة الـ Register. هنا بس بنتأكد إنه اتكتب، والسيرفر
  // هو اللي يقول صح ولا غلط.
  password: z.string().min(1, "اكتب الباسوورد"),
});

// =====================================================================
// registerSchema: فورم حساب المريض الجديد
// ---------------------------------------------------------------------
// z.object({...}) بيوصف كل خانة لوحدها، وبعدين .refine(...) في الآخر
// بيعمل تشييك بيقارن بين خانتين (الباسوورد وتأكيده).
// =====================================================================
export const registerSchema = z
  .object({
    // الاسم:
    // .trim()      → شيل المسافات من الأول والآخر قبل ما تعد الحروف.
    // .min(3, ...) → 3 حروف على الأقل (نفس القيد اللي في الداتابيز).
    // .max(80, ...)→ 80 حرف بالكتير، علشان محدش يلزق مقال في خانة الاسم.
    full_name: z.string().trim().min(3, "الاسم لازم يكون 3 حروف على الأقل").max(80, "الاسم طويل زيادة"),

    // الأيميل: نفس قاعدة الـ Login بالظبط.
    email: z.email("اكتب أيميل صحيح").trim().toLowerCase(),

    // الموبايل:
    // .regex(EG_MOBILE, ...) → لازم يطابق الـ regex اللي فوق.
    // ملحوظة: الـ schema بيتأكد من شكل الرقم بس. إن الرقم مش متسجل قبل
    // كده ده بيتعرف من السيرفر (is_phone_registered) بعد الـ validation.
    phone: z.string().trim().regex(EG_MOBILE, "رقم موبايل مصري صحيح (11 رقم يبدأ بـ 01)"),

    // الباسوورد: 8 حروف على الأقل.
    // مش بنعمل .trim() هنا، لأن المسافة ممكن تكون جزء من الباسوورد فعلاً.
    password: z.string().min(8, "الباسوورد لازم يكون 8 حروف على الأقل"),

    // تأكيد الباسوورد: هنا بس بنقول إنه نص. المقارنة بالباسوورد نفسه
    // بتحصل تحت في .refine، لأن الخانة لوحدها متعرفش قيمة الخانة التانية.
    confirm_password: z.string(),

    // النوع:
    // z.enum([...]) → القيمة لازم تبقى واحدة من دول بالظبط. نفس قيم الـ enum
    // اللي اسمه gender في الداتابيز. لو اليوزر ماختارش حاجة، القيمة بتيجي
    // فاضية، فـ zod يرجع الرسالة "اختار النوع".
    gender: z.enum(["male", "female"], "اختار النوع"),

    // تاريخ الميلاد:
    // z.iso.date(...) → لازم يبقى تاريخ بصيغة YYYY-MM-DD، زي 1990-05-01.
    //                   ودي نفس الصيغة اللي <input type="date"> بيرجعها.
    // .refine(دالة, رسالة) → تشييك إحنا بنكتبه بنفسنا: الدالة بترجع
    //                   true لو القيمة تمام، و false لو لأ.
    //                   هنا: التاريخ مش في المستقبل، ومش أقدم من 120 سنة.
    date_of_birth: z.iso.date("اختار تاريخ الميلاد").refine((d) => {
      const date = new Date(d);
      const now = new Date();
      const oldest = new Date(now.getFullYear() - 120, now.getMonth(), now.getDate());
      return date <= now && date >= oldest;
    }, "تاريخ الميلاد مش منطقي"),

    // المرض المزمن (اختياري):
    // .max(200, ...)  → 200 حرف بالكتير.
    // .optional()     → الخانة ممكن متتبعتش خالص.
    // .default("")    → ولو متبعتتش، اعتبرها نص فاضي. والداتابيز بتحوّل
    //                   النص الفاضي لـ null، والفرونت بيعرضه "لا يوجد".
    chronic_disease: z.string().trim().max(200, "الوصف طويل زيادة").optional().default(""),
  })
  // .refine على الـ object كله: هنا نقدر نشوف كل الخانات مع بعض.
  //   (v) => v.password === v.confirm_password
  //       → لازم الباسوورد وتأكيده يبقوا زي بعض بالظبط.
  //   path: ["confirm_password"]
  //       → لو الشرط فشل، الرسالة تتحط تحت خانة "تأكيد الباسوورد"
  //         (من غير path، الرسالة مش هتبقى تحت أي خانة).
  .refine((v) => v.password === v.confirm_password, {
    path: ["confirm_password"],
    message: "الباسوورد مش متطابق",
  });

// =====================================================================
// Types وأدوات مساعدة للفورمز
// =====================================================================

// شكل الأخطاء اللي الفورم بيعرضها:
//   { email: ["اكتب أيميل صحيح"], phone: ["رقم موبايل مصري صحيح ..."] }
// كل خانة ليها لستة رسايل، والفورم بيعرض أول رسالة تحت الخانة.
// Partial معناها مش لازم كل الخانات تبقى موجودة، الخانات اللي فيها غلط بس.
export type FieldErrors = Partial<Record<string, string[]>>;

// بتحوّل الخطأ اللي zod بيرجعه للشكل اللي فوق.
// z.flattenError(error).fieldErrors بيرجع object مفاتيحه أسامي الخانات.
// الفورم بيستخدمها كده:
//
//   const parsed = registerSchema.safeParse(form);
//   if (!parsed.success) return setFe(fieldErrorsOf(parsed.error));
export function fieldErrorsOf(error: z.ZodError): FieldErrors {
  return z.flattenError(error).fieldErrors as FieldErrors;
}
